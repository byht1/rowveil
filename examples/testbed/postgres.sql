-- Roostbase testbed: PostgreSQL.
-- Covers every studio feature: schemas, enums, identity/serial, generated columns, arrays,
-- jsonb and JSON stored as TEXT, big integers, composite keys, tables without a primary key,
-- awkward identifiers, wide and long tables, views, a materialized view, indexes of every kind,
-- triggers, roles, grants and row-level security.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SCHEMA billing;
CREATE SCHEMA analytics;

-- ---------------------------------------------------------------- enums
CREATE TYPE user_role AS ENUM ('owner', 'admin', 'editor', 'viewer');
CREATE TYPE order_status AS ENUM ('draft', 'pending', 'paid', 'shipped', 'cancelled', 'refunded');
CREATE TYPE billing.plan_tier AS ENUM ('free', 'pro', 'team', 'enterprise');

-- ---------------------------------------------------------------- core
CREATE TABLE organizations (
  id         serial PRIMARY KEY,
  name       text NOT NULL,
  slug       text NOT NULL UNIQUE,
  country    char(2) NOT NULL DEFAULT 'UA',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE users (
  id          serial PRIMARY KEY,
  org_id      integer REFERENCES organizations(id) ON DELETE SET NULL,
  email       varchar(255) NOT NULL,
  full_name   text NOT NULL,
  role        user_role NOT NULL DEFAULT 'viewer',
  is_active   boolean NOT NULL DEFAULT true,
  balance     numeric(12, 2) NOT NULL DEFAULT 0 CHECK (balance >= -1000),
  tags        text[] NOT NULL DEFAULT '{}',
  settings    jsonb NOT NULL DEFAULT '{}'::jsonb,
  external_id uuid NOT NULL DEFAULT gen_random_uuid(),
  last_ip     inet,
  birthday    date,
  bio         text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_lower_key ON users (lower(email));
CREATE INDEX users_settings_gin ON users USING gin (settings);
CREATE INDEX users_active_idx ON users (org_id) WHERE is_active;

-- 1:1 with users; JSON kept as plain TEXT (like many app databases do)
CREATE TABLE profiles (
  user_id     integer PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  avatar_url  text,
  preferences text,            -- compact JSON in a text column
  raw_payload text             -- pretty-printed JSON in a text column
);

-- composite primary key
CREATE TABLE memberships (
  org_id     integer NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role       user_role NOT NULL DEFAULT 'viewer',
  joined_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, user_id)
);

CREATE TABLE products (
  id             integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  sku            varchar(32) NOT NULL UNIQUE,
  title          text NOT NULL,
  description    text,
  price          numeric(10, 2) NOT NULL CHECK (price >= 0),
  vat_rate       numeric(4, 2) NOT NULL DEFAULT 20.00,
  price_with_vat numeric(12, 2) GENERATED ALWAYS AS (round(price * (1 + vat_rate / 100), 2)) STORED,
  stock          integer NOT NULL DEFAULT 0,
  dimensions     integer[],
  attributes     jsonb,
  image          bytea,
  discontinued   boolean NOT NULL DEFAULT false
);

CREATE TABLE orders (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  status      order_status NOT NULL DEFAULT 'draft',
  total       numeric(12, 2) NOT NULL DEFAULT 0,
  currency    char(3) NOT NULL DEFAULT 'UAH',
  note        text,
  ship_window tstzrange,
  delivery_in interval,
  placed_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX orders_user_status_idx ON orders (user_id, status);
CREATE INDEX orders_placed_brin ON orders USING brin (placed_at);

CREATE TABLE order_items (
  order_id   bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  line_no    smallint NOT NULL,
  product_id integer NOT NULL REFERENCES products(id),
  qty        integer NOT NULL CHECK (qty > 0),
  unit_price numeric(10, 2) NOT NULL,
  PRIMARY KEY (order_id, line_no)
);

-- JSON configuration stored as text, including numbers beyond 2^53
CREATE TABLE app_config (
  id     serial PRIMARY KEY,
  name   text NOT NULL UNIQUE,
  params text NOT NULL
);

-- big integers and many types in one place
CREATE TABLE events (
  id          bigint PRIMARY KEY,         -- values above 2^53 test precision
  kind        text NOT NULL,
  payload     jsonb,
  source_ip   inet,
  duration    interval,
  happened_at timestamptz NOT NULL,
  day         date GENERATED ALWAYS AS ((happened_at AT TIME ZONE 'UTC')::date) STORED,
  checksum    bytea,
  trace_id    uuid
);

-- no primary key: read-only in the grid
CREATE TABLE audit_log (
  at      timestamptz NOT NULL DEFAULT now(),
  actor   text,
  action  text NOT NULL,
  details jsonb
);

-- awkward identifiers: spaces, upper case, reserved words
CREATE TABLE "Order Details" (
  "ID"      serial PRIMARY KEY,
  "user"    text,
  "order"   integer,
  "select"  boolean DEFAULT false,
  "Mixed Case Column" text,
  "з пробілом" text
);

-- a wide table: horizontal scrolling and column hiding
CREATE TABLE wide_metrics (
  id serial PRIMARY KEY,
  c01 integer, c02 integer, c03 integer, c04 integer, c05 integer, c06 integer, c07 integer, c08 integer,
  c09 numeric(8,2), c10 numeric(8,2), c11 numeric(8,2), c12 numeric(8,2), c13 numeric(8,2), c14 numeric(8,2),
  c15 text, c16 text, c17 text, c18 text, c19 text, c20 text,
  c21 boolean, c22 boolean, c23 date, c24 date, c25 timestamptz, c26 uuid, c27 jsonb, c28 text[]
);

-- a long table: pagination, sorting, filters
CREATE TABLE page_views (
  id         bigserial PRIMARY KEY,
  user_id    integer REFERENCES users(id) ON DELETE SET NULL,
  path       text NOT NULL,
  referrer   text,
  country    char(2),
  ms         integer NOT NULL,
  is_bot     boolean NOT NULL DEFAULT false,
  viewed_at  timestamptz NOT NULL
);
CREATE INDEX page_views_viewed_at_idx ON page_views (viewed_at DESC);

-- ---------------------------------------------------------------- billing schema (RLS)
CREATE TABLE billing.subscriptions (
  id         bigserial PRIMARY KEY,
  org_id     integer NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  tier       billing.plan_tier NOT NULL DEFAULT 'free',
  seats      integer NOT NULL DEFAULT 1 CHECK (seats > 0),
  renews_on  date,
  meta       jsonb
);

CREATE TABLE billing.invoices (
  id         bigserial PRIMARY KEY,
  org_id     integer NOT NULL REFERENCES public.organizations(id),
  amount     numeric(10, 2) NOT NULL,
  currency   char(3) NOT NULL DEFAULT 'USD',
  paid       boolean NOT NULL DEFAULT false,
  issued_on  date NOT NULL DEFAULT current_date,
  CONSTRAINT invoices_amount_positive CHECK (amount > 0)
);
CREATE INDEX invoices_unpaid_idx ON billing.invoices (org_id) WHERE NOT paid;

-- ---------------------------------------------------------------- trigger
CREATE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;
CREATE TRIGGER users_set_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();

