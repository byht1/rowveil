-- ---------------------------------------------------------------- views
CREATE VIEW active_users AS
  SELECT id, email, full_name, role, org_id FROM users WHERE is_active;

CREATE VIEW order_totals AS
  SELECT u.id AS user_id, u.full_name, count(o.id) AS orders, coalesce(sum(o.total), 0) AS spent
  FROM users u LEFT JOIN orders o ON o.user_id = u.id AND o.status IN ('paid', 'shipped')
  GROUP BY u.id, u.full_name;

CREATE MATERIALIZED VIEW analytics.daily_sales AS
  SELECT date_trunc('day', placed_at)::date AS day, count(*) AS orders, sum(total) AS revenue
  FROM orders WHERE status IN ('paid', 'shipped')
  GROUP BY 1 ORDER BY 1;

-- ---------------------------------------------------------------- roles, grants, RLS
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_reader') THEN CREATE ROLE app_reader LOGIN PASSWORD 'reader'; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_writer') THEN CREATE ROLE app_writer LOGIN PASSWORD 'writer' CONNECTION LIMIT 10; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'analyst') THEN CREATE ROLE analyst NOLOGIN; END IF;
END $$;

GRANT USAGE ON SCHEMA billing, analytics TO app_reader, app_writer, analyst;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO app_reader;
GRANT SELECT, INSERT, UPDATE, DELETE ON users, profiles, orders, order_items TO app_writer;
GRANT SELECT ON billing.invoices, billing.subscriptions TO app_reader, app_writer;
GRANT SELECT ON analytics.daily_sales TO analyst;
GRANT analyst TO app_reader;

ALTER TABLE billing.invoices ENABLE ROW LEVEL SECURITY;
CREATE POLICY invoices_paid_only ON billing.invoices AS PERMISSIVE FOR SELECT TO app_reader USING (paid);
CREATE POLICY invoices_writer_all ON billing.invoices AS PERMISSIVE FOR ALL TO app_writer USING (true) WITH CHECK (amount < 100000);
CREATE POLICY invoices_no_uah ON billing.invoices AS RESTRICTIVE FOR SELECT TO app_reader USING (currency <> 'UAH');

