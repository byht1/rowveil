"""Builds next/src/icons.rs from the stable UI's line icons (ICONS in static/app.js).

Run from the repository root:  python next/assets/gen_icons.py
"""
import re

JS = open('static/app.js', encoding='utf-8').read()
body = re.search(r'const ICONS = \{(.*?)\n\};', JS, re.S).group(1)
icons = re.findall(r"^\s*(\w+): '(.*?)',?$", body, re.M)
# A few extra glyphs the GPUI port needs (same 24x24 line style).
icons += [
    ('chevronRight', '<path d="m9 6 6 6-6 6"/>'),
    ('chevronUp', '<path d="m6 15 6-6 6 6"/>'),
    ('dots', '<path d="M5 12h.01M12 12h.01M19 12h.01"/>'),
    ('arrowUp', '<path d="M12 19V5M5 12l7-7 7 7"/>'),
    ('arrowDown', '<path d="M12 5v14M19 12l-7 7-7-7"/>'),
    ('save', '<path d="M5 3h11l5 5v11a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2z"/><path d="M7 3v6h8M7 21v-7h10v7"/>'),
    ('upload', '<path d="M12 21V9M7 14l5-5 5 5M4 3h16"/>'),
    ('info', '<circle cx="12" cy="12" r="9"/><path d="M12 11v5M12 8h.01"/>'),
]
out = ['// Generated by assets/gen_icons.py from static/app.js. Do not edit.', '',
       '/// The line icons of the stable UI: (name, SVG).', 'pub const ICONS: &[(&str, &str)] = &[']
for name, paths in icons:
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
           'stroke="#000" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">' + paths + '</svg>')
    out.append(f'    ({name!r}, r##"{svg}"##),'.replace("'", '"', 2))
out.append('];')
open('next/src/icons.rs', 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('wrote', len(icons), 'icons')
