//! Schema introspection for PostgreSQL, MySQL and SQLite.

use crate::db::{kind_from_type_name, sqlite_kind, Db, Dialect, Sql};
use anyhow::Result;
use serde::Serialize;
use std::collections::{BTreeMap, HashMap};

#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct ColumnRef {
    pub schema: String,
    pub table: String,
    pub column: String,
}

#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Column {
    pub name: String,
    pub data_type: String,
    /// PostgreSQL type without modifiers, used in CAST expressions.
    #[serde(skip)]
    pub cast_type: String,
    pub kind: String,
    pub nullable: bool,
    pub default: Option<String>,
    pub primary: bool,
    /// Value is generated by the database (serial, identity, auto_increment, computed).
    pub auto: bool,
    /// Column is computed (GENERATED ALWAYS AS ...) and cannot be written.
    pub generated: bool,
    pub enum_values: Option<Vec<String>>,
    pub references: Option<ColumnRef>,
}

#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct ForeignKey {
    pub name: String,
    pub columns: Vec<String>,
    pub ref_schema: String,
    pub ref_table: String,
    pub ref_columns: Vec<String>,
}

#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Index {
    pub name: String,
    pub columns: Vec<String>,
    pub unique: bool,
    pub definition: Option<String>,
}

#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Table {
    pub schema: String,
    pub name: String,
    /// "table" | "view" | "materialized_view" | "foreign_table"
    pub kind: String,
    pub columns: Vec<Column>,
    pub primary_key: Vec<String>,
    pub foreign_keys: Vec<ForeignKey>,
    pub indexes: Vec<Index>,
    pub row_estimate: Option<i64>,
}

#[derive(Serialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct DbSchema {
    pub dialect: Dialect,
    pub schemas: Vec<String>,
    pub default_schema: String,
    pub tables: Vec<Table>,
}

impl DbSchema {
    pub fn table(&self, schema: &str, name: &str) -> Option<&Table> {
        self.tables.iter().find(|t| t.schema == schema && t.name == name)
    }
}

const SEP: char = '\u{1f}';

fn s(v: &Option<String>) -> String {
    v.clone().unwrap_or_default()
}

fn split_sep(v: &Option<String>) -> Vec<String> {
    v.as_deref()
        .map(|x| x.split(SEP).map(str::to_string).collect())
        .unwrap_or_default()
}

pub async fn introspect(db: &Db) -> Result<DbSchema> {
    let mut schema = match db.dialect() {
        Dialect::Postgres => introspect_pg(db).await?,
        Dialect::Mysql => introspect_mysql(db).await?,
        Dialect::Sqlite => introspect_sqlite(db).await?,
    };
    // Attach single-column foreign keys to their columns.
    for t in &mut schema.tables {
        for fk in &t.foreign_keys {
            if fk.columns.len() == 1 && fk.ref_columns.len() == 1 {
                if let Some(c) = t.columns.iter_mut().find(|c| c.name == fk.columns[0]) {
                    c.references = Some(ColumnRef {
                        schema: fk.ref_schema.clone(),
                        table: fk.ref_table.clone(),
                        column: fk.ref_columns[0].clone(),
                    });
                }
            }
        }
        for c in &mut t.columns {
            c.primary = t.primary_key.contains(&c.name);
        }
    }
    Ok(schema)
}

type Key = (String, String);

async fn introspect_pg(db: &Db) -> Result<DbSchema> {
    let d = Dialect::Postgres;
    let sys = "n.nspname NOT IN ('pg_catalog','information_schema') AND n.nspname NOT LIKE 'pg_toast%' AND n.nspname NOT LIKE 'pg_temp%'";

    let default_schema = db
        .fetch_strings(&Sql::raw(d, "SELECT current_schema()::text"))
        .await?
        .first()
        .and_then(|r| r[0].clone())
        .unwrap_or_else(|| "public".into());

    let schemas: Vec<String> = db
        .fetch_strings(&Sql::raw(
            d,
            format!("SELECT n.nspname::text FROM pg_namespace n WHERE {sys} ORDER BY 1"),
        ))
        .await?
        .into_iter()
        .filter_map(|r| r[0].clone())
        .collect();

    let enums_rows = db
        .fetch_strings(&Sql::raw(
            d,
            "SELECT e.enumtypid::text, e.enumlabel::text FROM pg_enum e ORDER BY e.enumtypid, e.enumsortorder",
        ))
        .await?;
    let mut enums: HashMap<String, Vec<String>> = HashMap::new();
    for r in enums_rows {
        enums.entry(s(&r[0])).or_default().push(s(&r[1]));
    }

    let table_rows = db
        .fetch_strings(&Sql::raw(
            d,
            format!(
                "SELECT n.nspname::text, c.relname::text, c.relkind::text, c.reltuples::bigint::text
                 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                 WHERE c.relkind IN ('r','v','m','p','f') AND NOT c.relispartition AND {sys}
                 ORDER BY 1, 2"
            ),
        ))
        .await?;
    let mut tables: BTreeMap<Key, Table> = BTreeMap::new();
    for r in table_rows {
        let kind = match s(&r[2]).as_str() {
            "v" => "view",
            "m" => "materialized_view",
            "f" => "foreign_table",
            _ => "table",
        };
        let est = r[3].as_deref().and_then(|x| x.parse::<i64>().ok()).filter(|n| *n >= 0);
        tables.insert(
            (s(&r[0]), s(&r[1])),
            Table {
                schema: s(&r[0]),
                name: s(&r[1]),
                kind: kind.into(),
                columns: vec![],
                primary_key: vec![],
                foreign_keys: vec![],
                indexes: vec![],
                row_estimate: est,
            },
        );
    }

    let col_rows = db
        .fetch_strings(&Sql::raw(
            d,
            format!(
                "SELECT n.nspname::text, c.relname::text, a.attname::text,
                        pg_catalog.format_type(a.atttypid, a.atttypmod),
                        t.typname::text, t.typcategory::text, t.typtype::text,
                        (NOT a.attnotnull)::text, pg_get_expr(ad.adbin, ad.adrelid),
                        a.attidentity::text, a.attgenerated::text, a.atttypid::text,
                        pg_catalog.format_type(a.atttypid, NULL)
                 FROM pg_attribute a
                 JOIN pg_class c ON c.oid = a.attrelid
                 JOIN pg_namespace n ON n.oid = c.relnamespace
                 JOIN pg_type t ON t.oid = a.atttypid
                 LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
                 WHERE a.attnum > 0 AND NOT a.attisdropped
                   AND c.relkind IN ('r','v','m','p','f') AND NOT c.relispartition AND {sys}
                 ORDER BY 1, 2, a.attnum"
            ),
        ))
        .await?;
    for r in col_rows {
        let Some(t) = tables.get_mut(&(s(&r[0]), s(&r[1]))) else { continue };
        let typname = s(&r[4]);
        let category = s(&r[5]);
        let typtype = s(&r[6]);
        let default = r[8].clone();
        let identity = s(&r[9]);
        let generated = s(&r[10]) == "s";
        let kind = if category == "A" {
            "array".to_string()
        } else if typtype == "e" {
            "enum".to_string()
        } else {
            kind_from_type_name(d, &typname)
        };
        let serial = default.as_deref().map(|x| x.starts_with("nextval(")).unwrap_or(false);
        t.columns.push(Column {
            name: s(&r[2]),
            data_type: s(&r[3]),
            cast_type: s(&r[12]),
            kind,
            nullable: s(&r[7]) == "true",
            default: if generated { None } else { default.clone() },
            primary: false,
            auto: serial || !identity.is_empty() || generated,
            generated: generated || identity == "a",
            enum_values: if typtype == "e" { enums.get(&s(&r[11])).cloned() } else { None },
            references: None,
        });
    }

    let con_rows = db
        .fetch_strings(&Sql::raw(
            d,
            format!(
                "SELECT n.nspname::text, c.relname::text, con.contype::text, con.conname::text,
                   (SELECT string_agg(a.attname::text, chr(31) ORDER BY k.ord)
                      FROM unnest(con.conkey) WITH ORDINALITY k(attnum, ord)
                      JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum),
                   fn.nspname::text, fc.relname::text,
                   (SELECT string_agg(a.attname::text, chr(31) ORDER BY k.ord)
                      FROM unnest(con.confkey) WITH ORDINALITY k(attnum, ord)
                      JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.attnum)
                 FROM pg_constraint con
                 JOIN pg_class c ON c.oid = con.conrelid
                 JOIN pg_namespace n ON n.oid = c.relnamespace
                 LEFT JOIN pg_class fc ON fc.oid = con.confrelid
                 LEFT JOIN pg_namespace fn ON fn.oid = fc.relnamespace
                 WHERE con.contype IN ('p','f') AND {sys}
                 ORDER BY 1, 2, 4"
            ),
        ))
        .await?;
    for r in con_rows {
        let Some(t) = tables.get_mut(&(s(&r[0]), s(&r[1]))) else { continue };
        if s(&r[2]) == "p" {
            t.primary_key = split_sep(&r[4]);
        } else {
            t.foreign_keys.push(ForeignKey {
                name: s(&r[3]),
                columns: split_sep(&r[4]),
                ref_schema: s(&r[5]),
                ref_table: s(&r[6]),
                ref_columns: split_sep(&r[7]),
            });
        }
    }

    let idx_rows = db
        .fetch_strings(&Sql::raw(
            d,
            format!(
                "SELECT n.nspname::text, c.relname::text, i.relname::text, ix.indisunique::text,
                   pg_get_indexdef(ix.indexrelid),
                   (SELECT string_agg(pg_get_indexdef(ix.indexrelid, k.ord::int, true), chr(31) ORDER BY k.ord)
                      FROM generate_subscripts(ix.indkey, 1) WITH ORDINALITY k(sub, ord))
                 FROM pg_index ix
                 JOIN pg_class c ON c.oid = ix.indrelid
                 JOIN pg_class i ON i.oid = ix.indexrelid
                 JOIN pg_namespace n ON n.oid = c.relnamespace
                 WHERE {sys}
                 ORDER BY 1, 2, 3"
            ),
        ))
        .await?;
    for r in idx_rows {
        let Some(t) = tables.get_mut(&(s(&r[0]), s(&r[1]))) else { continue };
        t.indexes.push(Index {
            name: s(&r[2]),
            unique: s(&r[3]) == "true",
            definition: r[4].clone(),
            columns: split_sep(&r[5]),
        });
    }

    Ok(DbSchema {
        dialect: d,
        schemas,
        default_schema,
        tables: tables.into_values().collect(),
    })
}

async fn introspect_mysql(db: &Db) -> Result<DbSchema> {
    let d = Dialect::Mysql;
    let sys = "('mysql','information_schema','performance_schema','sys')";

    let current = db
        .fetch_strings(&Sql::raw(d, "SELECT CAST(DATABASE() AS CHAR)"))
        .await?
        .first()
        .and_then(|r| r[0].clone());

    let schemas: Vec<String> = db
        .fetch_strings(&Sql::raw(
            d,
            format!("SELECT CAST(SCHEMA_NAME AS CHAR) FROM information_schema.SCHEMATA WHERE SCHEMA_NAME NOT IN {sys} ORDER BY 1"),
        ))
        .await?
        .into_iter()
        .filter_map(|r| r[0].clone())
        .collect();

    let table_rows = db
        .fetch_strings(&Sql::raw(
            d,
            format!(
                "SELECT CAST(TABLE_SCHEMA AS CHAR), CAST(TABLE_NAME AS CHAR), CAST(TABLE_TYPE AS CHAR), CAST(TABLE_ROWS AS CHAR)
                 FROM information_schema.TABLES WHERE TABLE_SCHEMA NOT IN {sys} ORDER BY 1, 2"
            ),
        ))
        .await?;
    let mut tables: BTreeMap<Key, Table> = BTreeMap::new();
    for r in table_rows {
        let kind = if s(&r[2]).contains("VIEW") { "view" } else { "table" };
        tables.insert(
            (s(&r[0]), s(&r[1])),
            Table {
                schema: s(&r[0]),
                name: s(&r[1]),
                kind: kind.into(),
                columns: vec![],
                primary_key: vec![],
                foreign_keys: vec![],
                indexes: vec![],
                row_estimate: r[3].as_deref().and_then(|x| x.parse().ok()),
            },
        );
    }

    let col_rows = db
        .fetch_strings(&Sql::raw(
            d,
            format!(
                "SELECT CAST(TABLE_SCHEMA AS CHAR), CAST(TABLE_NAME AS CHAR), CAST(COLUMN_NAME AS CHAR),
                        CAST(COLUMN_TYPE AS CHAR), CAST(DATA_TYPE AS CHAR), CAST(IS_NULLABLE AS CHAR),
                        CAST(COLUMN_DEFAULT AS CHAR), CAST(EXTRA AS CHAR)
                 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA NOT IN {sys}
                 ORDER BY TABLE_SCHEMA, TABLE_NAME, ORDINAL_POSITION"
            ),
        ))
        .await?;
    for r in col_rows {
        let Some(t) = tables.get_mut(&(s(&r[0]), s(&r[1]))) else { continue };
        let column_type = s(&r[3]);
        let data_type = s(&r[4]).to_ascii_lowercase();
        let extra = s(&r[7]).to_ascii_lowercase();
        let generated = extra.contains("virtual generated") || extra.contains("stored generated");
        let (kind, enum_values) = if data_type == "enum" {
            ("enum".to_string(), Some(parse_mysql_enum(&column_type)))
        } else if column_type.to_ascii_lowercase().starts_with("tinyint(1)") {
            ("boolean".to_string(), None)
        } else {
            (kind_from_type_name(d, &data_type), None)
        };
        t.columns.push(Column {
            name: s(&r[2]),
            data_type: column_type.clone(),
            cast_type: column_type,
            kind,
            nullable: s(&r[5]) == "YES",
            default: r[6].clone(),
            primary: false,
            auto: extra.contains("auto_increment") || generated,
            generated,
            enum_values,
            references: None,
        });
    }

    let key_rows = db
        .fetch_strings(&Sql::raw(
            d,
            format!(
                "SELECT CAST(TABLE_SCHEMA AS CHAR), CAST(TABLE_NAME AS CHAR), CAST(CONSTRAINT_NAME AS CHAR),
                        CAST(COLUMN_NAME AS CHAR), CAST(REFERENCED_TABLE_SCHEMA AS CHAR),
                        CAST(REFERENCED_TABLE_NAME AS CHAR), CAST(REFERENCED_COLUMN_NAME AS CHAR)
                 FROM information_schema.KEY_COLUMN_USAGE
                 WHERE TABLE_SCHEMA NOT IN {sys} AND (CONSTRAINT_NAME = 'PRIMARY' OR REFERENCED_TABLE_NAME IS NOT NULL)
                 ORDER BY TABLE_SCHEMA, TABLE_NAME, CONSTRAINT_NAME, ORDINAL_POSITION"
            ),
        ))
        .await?;
    for r in key_rows {
        let Some(t) = tables.get_mut(&(s(&r[0]), s(&r[1]))) else { continue };
        let name = s(&r[2]);
        let col = s(&r[3]);
        if name == "PRIMARY" {
            t.primary_key.push(col);
            continue;
        }
        if let Some(fk) = t.foreign_keys.iter_mut().find(|f| f.name == name) {
            fk.columns.push(col);
            fk.ref_columns.push(s(&r[6]));
        } else {
            t.foreign_keys.push(ForeignKey {
                name,
                columns: vec![col],
                ref_schema: s(&r[4]),
                ref_table: s(&r[5]),
                ref_columns: vec![s(&r[6])],
            });
        }
    }

    let idx_rows = db
        .fetch_strings(&Sql::raw(
            d,
            format!(
                "SELECT CAST(TABLE_SCHEMA AS CHAR), CAST(TABLE_NAME AS CHAR), CAST(INDEX_NAME AS CHAR),
                        CAST(NON_UNIQUE AS CHAR), CAST(COLUMN_NAME AS CHAR)
                 FROM information_schema.STATISTICS WHERE TABLE_SCHEMA NOT IN {sys}
                 ORDER BY TABLE_SCHEMA, TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX"
            ),
        ))
        .await?;
    for r in idx_rows {
        let Some(t) = tables.get_mut(&(s(&r[0]), s(&r[1]))) else { continue };
        let name = s(&r[2]);
        let col = r[4].clone().unwrap_or_else(|| "(expression)".into());
        if let Some(ix) = t.indexes.iter_mut().find(|i| i.name == name) {
            ix.columns.push(col);
        } else {
            t.indexes.push(Index { name, columns: vec![col], unique: s(&r[3]) == "0", definition: None });
        }
    }

    let default_schema = current
        .or_else(|| schemas.first().cloned())
        .unwrap_or_default();
    Ok(DbSchema { dialect: d, schemas, default_schema, tables: tables.into_values().collect() })
}

fn parse_mysql_enum(column_type: &str) -> Vec<String> {
    // enum('a','b','it''s')
    let Some(start) = column_type.find('(') else { return vec![] };
    let inner = &column_type[start + 1..column_type.len().saturating_sub(1)];
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut in_q = false;
    let mut chars = inner.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '\'' if in_q && chars.peek() == Some(&'\'') => {
                cur.push('\'');
                chars.next();
            }
            '\'' => {
                if in_q {
                    out.push(std::mem::take(&mut cur));
                }
                in_q = !in_q;
            }
            _ if in_q => cur.push(c),
            _ => {}
        }
    }
    out
}

async fn introspect_sqlite(db: &Db) -> Result<DbSchema> {
    let d = Dialect::Sqlite;
    let table_rows = db
        .fetch_strings(&Sql::raw(
            d,
            "SELECT name, type FROM sqlite_master WHERE type IN ('table','view') AND name NOT LIKE 'sqlite_%' ORDER BY name",
        ))
        .await?;
    let mut tables = Vec::new();
    for r in table_rows {
        let name = s(&r[0]);
        let kind = if s(&r[1]) == "view" { "view" } else { "table" };

        let mut q = Sql::new(d);
        let p = q.param(Some(name.clone()));
        q.push(&format!(
            "SELECT name, type, \"notnull\", dflt_value, pk, hidden FROM pragma_table_xinfo({p}) ORDER BY cid"
        ));
        let cols = db.fetch_strings(&q).await?;
        let mut pk: Vec<(i64, String)> = Vec::new();
        let mut columns = Vec::new();
        for c in &cols {
            let cname = s(&c[0]);
            let ctype = s(&c[1]);
            let pk_pos: i64 = c[4].as_deref().and_then(|x| x.parse().ok()).unwrap_or(0);
            let hidden: i64 = c[5].as_deref().and_then(|x| x.parse().ok()).unwrap_or(0);
            if hidden == 1 {
                continue; // hidden column of a virtual table
            }
            if pk_pos > 0 {
                pk.push((pk_pos, cname.clone()));
            }
            let generated = hidden == 2 || hidden == 3;
            columns.push(Column {
                name: cname,
                kind: sqlite_kind(&ctype),
                data_type: if ctype.is_empty() { "any".into() } else { ctype.clone() },
                cast_type: ctype.clone(),
                nullable: s(&c[2]) != "1",
                default: c[3].clone(),
                primary: false,
                auto: generated,
                generated,
                enum_values: None,
                references: None,
            });
        }
        pk.sort();
        let primary_key: Vec<String> = pk.into_iter().map(|(_, n)| n).collect();
        // INTEGER PRIMARY KEY is an alias for rowid -> auto-generated.
        if primary_key.len() == 1 {
            if let Some(c) = columns.iter_mut().find(|c| c.name == primary_key[0]) {
                if c.data_type.eq_ignore_ascii_case("INTEGER") {
                    c.auto = true;
                }
            }
        }

        let mut q = Sql::new(d);
        let p = q.param(Some(name.clone()));
        q.push(&format!(
            "SELECT id, \"table\", \"from\", \"to\" FROM pragma_foreign_key_list({p}) ORDER BY id, seq"
        ));
        let mut foreign_keys: Vec<ForeignKey> = Vec::new();
        let mut last_id: Option<String> = None;
        for f in db.fetch_strings(&q).await? {
            let id = s(&f[0]);
            if last_id.as_deref() == Some(id.as_str()) {
                let fk = foreign_keys.last_mut().unwrap();
                fk.columns.push(s(&f[2]));
                fk.ref_columns.push(s(&f[3]));
            } else {
                let ref_table = s(&f[1]);
                foreign_keys.push(ForeignKey {
                    name: format!("fk_{name}_{id}"),
                    columns: vec![s(&f[2])],
                    ref_schema: "main".into(),
                    ref_table,
                    ref_columns: vec![s(&f[3])],
                });
                last_id = Some(id);
            }
        }

        let mut q = Sql::new(d);
        let p = q.param(Some(name.clone()));
        q.push(&format!(
            "SELECT il.name, il.\"unique\", (SELECT group_concat(ii.name, char(31)) FROM pragma_index_info(il.name) ii), m.sql
             FROM pragma_index_list({p}) il LEFT JOIN sqlite_master m ON m.name = il.name AND m.type = 'index'"
        ));
        let indexes = db
            .fetch_strings(&q)
            .await?
            .into_iter()
            .map(|i| Index {
                name: s(&i[0]),
                unique: s(&i[1]) == "1",
                columns: split_sep(&i[2]),
                definition: i[3].clone(),
            })
            .collect();

        tables.push(Table {
            schema: "main".into(),
            name,
            kind: kind.into(),
            columns,
            primary_key,
            foreign_keys,
            indexes,
            row_estimate: None,
        });
    }
    // Resolve referenced primary keys for FKs that omit target columns.
    let pks: HashMap<String, Vec<String>> =
        tables.iter().map(|t| (t.name.clone(), t.primary_key.clone())).collect();
    for t in &mut tables {
        for fk in &mut t.foreign_keys {
            if fk.ref_columns.iter().all(|c| c.is_empty()) {
                if let Some(p) = pks.get(&fk.ref_table) {
                    fk.ref_columns = p.clone();
                }
            }
        }
    }
    Ok(DbSchema { dialect: d, schemas: vec!["main".into()], default_schema: "main".into(), tables })
}

